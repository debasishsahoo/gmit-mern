
let x= 10;// Basic assignment

x+= 5;// x = x + 5  -> 15
console.log(x);// 15
x-= 3;// x = x - 3  -> 12
console.log(x);// 12
x*= 2;// x = x * 2  -> 24
console.log(x);// 24
x/= 4;// x = x / 4  -> 6
console.log(x);// 6
x%= 4;// x = x % 4  -> 2
console.log(x);// 2
x**= 3;// x = x ** 3 -> 8
console.log(x);// 8